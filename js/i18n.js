(function() {
    var storedLang = 'en';
    try {
        storedLang = localStorage.getItem('poli_tools_language') || 'en';
    } catch(e) {}
    if (!window.I18N || !window.I18N[storedLang]) {
        storedLang = 'en';
    }
    window.currentLang = storedLang;

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', window.applyTranslations);
    } else {
        window.applyTranslations();
    }
})();
