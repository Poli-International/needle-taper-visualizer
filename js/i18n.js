window.currentLang = 'en';

window.t = function(key, params) {
    if (!key) return '';
    var dict = (window.I18N && window.I18N[window.currentLang]) || (window.I18N && window.I18N.en) || {};
    var str = (dict && dict[key]) || (window.I18N && window.I18N.en && window.I18N.en[key]) || key;
    if (params && typeof str === 'string') {
        Object.keys(params).forEach(function(p) {
            str = str.replace(new RegExp('\\{' + p + '\\}', 'g'), params[p]);
        });
    }
    return str;
};

window.applyTranslations = function() {
    // 1. Text elements with data-i18n
    var elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        if (key) {
            el.textContent = window.t(key);
        }
    });

    // 2. Attributes specified in data-i18n-attr (e.g. "aria-label:header.theme_toggle")
    var attrElements = document.querySelectorAll('[data-i18n-attr]');
    attrElements.forEach(function(el) {
        var spec = el.getAttribute('data-i18n-attr');
        if (spec) {
            spec.split(';').forEach(function(pair) {
                var parts = pair.split(':');
                if (parts.length === 2) {
                    var attr = parts[0].trim();
                    var key = parts[1].trim();
                    el.setAttribute(attr, window.t(key));
                }
            });
        }
    });

    // 3. Document title
    document.title = window.t('app.title');

    // 4. Update dynamic visuals if available
    if (typeof window.updateVisuals === 'function') {
        window.updateVisuals();
    }
};

window.setLanguage = function(lang) {
    if (!window.I18N || !window.I18N[lang]) {
        lang = 'en';
    }
    window.currentLang = lang;
    try {
        localStorage.setItem('poli_tools_language', lang);
    } catch(e) {}

    var select = document.getElementById('lang-select');
    if (select && select.value !== lang) {
        select.value = lang;
    }

    window.applyTranslations();
};

